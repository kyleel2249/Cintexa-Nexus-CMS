const { onCall, HttpsError } = require('firebase-functions/v2/https');
const { db, admin } = require('../lib/admin');
const { requireAuthContext } = require('../lib/rbac');
const { logAudit } = require('../lib/audit');

const COLLECTION_BY_TYPE = {
  asset_inventory: 'assets',
  attack_surface: 'attack_surface_observations',
  vulnerability: 'vulnerability_findings',
  website_security: 'scans',
  network_security: 'scans',
  api_security: 'scans',
  pentest: 'pentest_engagements',
};

/**
 * Server-side report generation: fetches the tenant-scoped dataset for the
 * requested report type and logs the generation event. The actual
 * PDF/CSV/XLSX file is assembled client-side (public/assets/js/modules/
 * reports.js) from this same tenant-scoped data using jsPDF/SheetJS, which
 * keeps heavy document-layout work off the Functions runtime. This
 * callable exists as the audited, authoritative record of "a report of
 * type X with N rows was generated by user Y at time Z" and as an
 * API-accessible report source for programmatic integrations.
 */
const generateReport = onCall(async (request) => {
  const ctx = requireAuthContext(request, 'report.generate');
  const { type, format } = request.data || {};
  const collectionName = COLLECTION_BY_TYPE[type];
  if (!collectionName) throw new HttpsError('invalid-argument', `Unknown report type "${type}".`);

  const snap = await db.collection(collectionName).where('tenantId', '==', ctx.tenantId).limit(1000).get();
  const rows = snap.docs.map((d) => ({ id: d.id, ...d.data() }));

  const reportRef = db.collection('reports').doc();
  await reportRef.set({
    tenantId: ctx.tenantId, reportType: type, format: format || 'data', rowCount: rows.length,
    generatedByUid: ctx.uid, generatedByEmail: ctx.email, createdAt: admin.firestore.FieldValue.serverTimestamp(),
  });

  await logAudit({ tenantId: ctx.tenantId, action: 'report.generated', actorUid: ctx.uid, actorEmail: ctx.email, targetType: 'report', targetId: reportRef.id, summary: `Generated ${type} report (${rows.length} rows)` });
  return { reportId: reportRef.id, rows };
});

module.exports = { generateReport };
