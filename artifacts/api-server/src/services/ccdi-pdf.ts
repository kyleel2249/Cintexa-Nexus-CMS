/**
 * CINTEXA CCDI — Phase 15 minimal PDF builder (no external PDF library).
 * Produces a valid multi-page text PDF for report export.
 */

function escapePdfText(s: string): string {
  return String(s)
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)")
    .replace(/[^\x20-\x7E\n]/g, "?");
}

function wrapLines(text: string, maxChars: number): string[] {
  const out: string[] = [];
  for (const raw of String(text).split("\n")) {
    let line = raw;
    while (line.length > maxChars) {
      let breakAt = line.lastIndexOf(" ", maxChars);
      if (breakAt < 20) breakAt = maxChars;
      out.push(line.slice(0, breakAt));
      line = line.slice(breakAt).trimStart();
    }
    out.push(line);
  }
  return out;
}

export function buildSimplePdf(opts: {
  title: string;
  subtitle?: string;
  lines: string[];
}): Buffer {
  const pageWidth = 612;
  const pageHeight = 792;
  const margin = 50;
  const lineHeight = 12;
  const maxChars = 90;
  const maxLinesPerPage = Math.floor((pageHeight - margin * 2 - 24) / lineHeight);

  const allLines = [
    ...wrapLines(opts.title, maxChars),
    ...wrapLines(opts.subtitle || "CINTEXA CCDI Report", maxChars),
    ...wrapLines(`Generated: ${new Date().toISOString()}`, maxChars),
    ...wrapLines("Evidence-backed data only. No fabricated statistics.", maxChars),
    "",
    ...opts.lines.flatMap((l) => wrapLines(l, maxChars)),
  ];

  const pages: string[][] = [];
  for (let i = 0; i < allLines.length; i += maxLinesPerPage) {
    pages.push(allLines.slice(i, i + maxLinesPerPage));
  }
  if (!pages.length) pages.push(["(empty report)"]);

  type Obj = { id: number; body: string };
  const objs: Obj[] = [];
  const alloc = () => {
    const id = objs.length + 1;
    objs.push({ id, body: "" });
    return id;
  };

  const fontId = alloc();
  objs[fontId - 1]!.body = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>";

  const pageIds: number[] = [];
  for (const pageLines of pages) {
    const y = pageHeight - margin;
    const ops: string[] = ["BT", "/F1 10 Tf", `${margin} ${y} Td`, `${lineHeight} TL`];
    pageLines.forEach((line, idx) => {
      const t = escapePdfText(line);
      if (idx === 0) ops.push(`(${t}) Tj`);
      else {
        ops.push("T*");
        ops.push(`(${t}) Tj`);
      }
    });
    ops.push("ET");
    const stream = ops.join("\n");
    const contentId = alloc();
    objs[contentId - 1]!.body =
      `<< /Length ${Buffer.byteLength(stream, "utf8")} >>\nstream\n${stream}\nendstream`;

    const pageId = alloc();
    objs[pageId - 1]!.body = `<< /Type /Page /Parent PAGES_ID 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /Font << /F1 ${fontId} 0 R >> >> /Contents ${contentId} 0 R >>`;
    pageIds.push(pageId);
  }

  const pagesId = alloc();
  objs[pagesId - 1]!.body =
    `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(" ")}] /Count ${pageIds.length} >>`;

  const catalogId = alloc();
  objs[catalogId - 1]!.body = `<< /Type /Catalog /Pages ${pagesId} 0 R >>`;

  // Patch parent refs
  for (const o of objs) {
    if (o.body.includes("PAGES_ID")) {
      o.body = o.body.replace(/PAGES_ID/g, String(pagesId));
    }
  }

  let pdf = "%PDF-1.4\n";
  const xref: number[] = [];
  for (const o of objs) {
    xref[o.id] = Buffer.byteLength(pdf, "utf8");
    pdf += `${o.id} 0 obj\n${o.body}\nendobj\n`;
  }
  const xrefStart = Buffer.byteLength(pdf, "utf8");
  const maxId = objs[objs.length - 1]!.id;
  pdf += `xref\n0 ${maxId + 1}\n`;
  pdf += "0000000000 65535 f \n";
  for (let i = 1; i <= maxId; i++) {
    const off = xref[i] ?? 0;
    pdf += `${String(off).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${maxId + 1} /Root ${catalogId} 0 R >>\n`;
  pdf += `startxref\n${xrefStart}\n%%EOF\n`;

  return Buffer.from(pdf, "utf8");
}

export function reportToPdfLines(report: {
  title: string;
  report_type?: string;
  generated_at?: string;
  generated_by?: string;
  summary?: unknown;
  sections?: Array<{ heading?: string; body?: unknown }>;
}): { title: string; subtitle: string; lines: string[] } {
  const lines: string[] = [];
  lines.push(`Type: ${report.report_type || "report"}`);
  if (report.generated_by) lines.push(`Generated by: ${report.generated_by}`);
  lines.push("");
  lines.push("=== SUMMARY ===");
  lines.push(JSON.stringify(report.summary ?? {}, null, 2));
  const sections = Array.isArray(report.sections) ? report.sections : [];
  for (const sec of sections) {
    lines.push("");
    lines.push(`=== ${sec.heading || "Section"} ===`);
    lines.push(JSON.stringify(sec.body ?? {}, null, 2));
  }
  return {
    title: report.title || "CCDI Report",
    subtitle: "CINTEXA Advanced Cyber Defense & Security Intelligence",
    lines,
  };
}
