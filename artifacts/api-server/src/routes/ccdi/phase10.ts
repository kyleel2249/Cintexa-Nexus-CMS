/**
 * CINTEXA CCDI — Phase 10 routes
 * Connector health, report export, deployment readiness snapshot
 */
import { Router, type Request, type Response } from "express";
import { pool } from "@workspace/db";
import { requireAuth } from "../../lib/auth-middleware";
import { logger } from "../../lib/logger";
import * as connectors from "../../services/ccdi-connectors";
import * as reporting from "../../services/ccdi-reporting";

const router = Router();

// ── Connector health ───────────────────────────────────────────────────────
router.post("/connectors/:id/health", requireAuth, async (req: Request, res: Response) => {
  try {
    const orgId = typeof req.body?.organizationId === "string" ? req.body.organizationId : undefined;
    const out = await connectors.checkConnectorHealth(req.params.id, orgId);
    if (out.error) {
      res.status(out.status ?? 400).json({ error: out.error });
      return;
    }
    res.json({
      ...out.result,
      note: "Local configuration checks only. No network probes against assets.",
    });
  } catch (err) {
    logger.error({ err }, "ccdi.connectors.health failed");
    res.status(500).json({ error: "Health check failed" });
  }
});

router.post("/connectors/health-all", requireAuth, async (req: Request, res: Response) => {
  try {
    const orgId = typeof req.body?.organizationId === "string" ? req.body.organizationId : undefined;
    const results = await connectors.checkAllConnectors(orgId);
    res.json({
      results,
      note: "Local configuration checks only. No live scanning.",
    });
  } catch (err) {
    logger.error({ err }, "ccdi.connectors.health-all failed");
    res.status(500).json({ error: "Bulk health check failed" });
  }
});

// ── Report export (JSON or Markdown) ───────────────────────────────────────
router.get("/reporting/reports/:id/export", requireAuth, async (req: Request, res: Response) => {
  try {
    const format = (typeof req.query.format === "string" ? req.query.format : "json").toLowerCase();
    const { rows } = await pool.query(`SELECT * FROM ccdi_reports WHERE id = $1`, [req.params.id]);
    if (!rows[0]) {
      res.status(404).json({ error: "Report not found" });
      return;
    }
    const report = rows[0];

    if (format === "markdown" || format === "md") {
      const md = renderReportMarkdown(report);
      res.setHeader("Content-Type", "text/markdown; charset=utf-8");
      res.setHeader(
        "Content-Disposition",
        `attachment; filename="ccdi-report-${report.id.slice(0, 8)}.md"`,
      );
      res.send(md);
      return;
    }

    res.setHeader("Content-Type", "application/json; charset=utf-8");
    res.setHeader(
      "Content-Disposition",
      `attachment; filename="ccdi-report-${report.id.slice(0, 8)}.json"`,
    );
    res.send(JSON.stringify(report, null, 2));
  } catch (err) {
    logger.error({ err }, "ccdi.reporting.export failed");
    res.status(500).json({ error: "Export failed" });
  }
});

function renderReportMarkdown(report: any): string {
  const lines: string[] = [];
  lines.push(`# ${report.title}`);
  lines.push("");
  lines.push(`- **Type:** ${report.report_type}`);
  lines.push(`- **Generated:** ${report.generated_at}`);
  lines.push(`- **By:** ${report.generated_by ?? "n/a"}`);
  lines.push(`- **Status:** ${report.status}`);
  lines.push("");
  lines.push("## Summary");
  lines.push("```json");
  lines.push(JSON.stringify(report.summary ?? {}, null, 2));
  lines.push("```");
  lines.push("");
  const sections = Array.isArray(report.sections) ? report.sections : [];
  for (const sec of sections) {
    lines.push(`## ${sec.heading ?? "Section"}`);
    lines.push("```json");
    lines.push(JSON.stringify(sec.body ?? {}, null, 2));
    lines.push("```");
    lines.push("");
  }
  lines.push("---");
  lines.push("_Generated by CINTEXA CCDI. Evidence-backed data only._");
  return lines.join("\n");
}

// ── Deployment readiness snapshot ──────────────────────────────────────────
router.get("/readiness", requireAuth, async (_req: Request, res: Response) => {
  try {
    // Ensure phase-7 tables exist for counts
    for (const stmt of reporting.CCDI_PHASE7_SCHEMA) {
      await pool.query(stmt).catch(() => undefined);
    }

    const [orgs, jobs, findings, kill] = await Promise.all([
      pool.query(`SELECT count(*)::int AS n FROM ccdi_organizations WHERE status = 'active'`),
      pool.query(`SELECT count(*)::int AS n FROM ccdi_jobs`),
      pool.query(`SELECT count(*)::int AS n FROM ccdi_findings`).catch(() => ({ rows: [{ n: 0 }] })),
      pool.query(`SELECT active FROM ccdi_kill_switch WHERE id = 1`),
    ]);

    const strictRbac = process.env.CCDI_STRICT_RBAC === "1" || process.env.CCDI_STRICT_RBAC === "true";

    res.json({
      phase: 10,
      readyFor: {
        controlPlane: true,
        advisoryAi: Boolean(process.env.OPENROUTER_API_KEY),
        liveScanning: false,
        unattendedInternetFacingScanners: false,
      },
      checks: {
        databaseReachable: true,
        killSwitchActive: Boolean(kill.rows[0]?.active),
        strictRbacEnv: strictRbac,
        openRouterConfigured: Boolean(process.env.OPENROUTER_API_KEY),
        activeOrganizations: orgs.rows[0]?.n ?? 0,
        jobsTotal: jobs.rows[0]?.n ?? 0,
        findingsTotal: findings.rows[0]?.n ?? 0,
      },
      operatorActions: [
        "Set DATABASE_URL and run bootstrap",
        "Configure authentication (Firebase/JWT)",
        "Optionally set OPENROUTER_API_KEY for advisory agents",
        "POST /api/ccdi/rbac/seed and assign roles",
        "Set CCDI_STRICT_RBAC=1 only after roles are assigned",
        "Do not expose worker claim endpoints without network controls",
      ],
      note: "Readiness reflects control-plane capability. Live scanners are not enabled.",
    });
  } catch (err) {
    logger.error({ err }, "ccdi.readiness failed");
    res.status(500).json({
      phase: 10,
      readyFor: { controlPlane: false, liveScanning: false },
      error: "Readiness probe failed — check DATABASE_URL",
    });
  }
});

export default router;
